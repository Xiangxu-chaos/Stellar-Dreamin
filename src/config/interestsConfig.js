/**
 * interestsConfig.js
 * ============================================================================
 * 兴趣领域（Interest Domain）总配置。
 *
 * 设计目标（为「最终版」预留扩展点）：
 *   - 最终版支持任意兴趣领域：游戏、动漫、电影、体育、编程、美食、旅行……
 *   - 每个领域拥有独立的：专有术语表(domainTerms)、视觉主题(theme)、生成 prompt。
 *   - 用户可以自行添加兴趣领域（未来只需往 INTEREST_DOMAINS 里 push 一个对象，
 *     或由 dataService 从 localStorage / 后端读取用户自定义领域后合并进来）。
 *
 * 关键约定：
 *   1. 所有领域配置一律以「数据」形式存在，任何页面/逻辑都不得写死
 *      「如果是 X 领域就怎样」，只能从配置对象里读字段。
 *   2. 术语表字段名统一为 domainTerms（泛化命名），不要叫 gameTerms。
 *      未来动漫领域同样叫 domainTerms，语义 =「该领域的专有名词 → 官方中文译名」。
 *   3. theme 为纯设计 token（CSS 变量键值），页面只负责把 token 写进
 *      :root 的 CSS 变量，不关心它是哪部作品。
 *   4. 术语表分两部分：
 *      - domainTerms:      专有名词 → 官方中文译名（用于命中判定 + 展示正确译名）
 *      - domainVocabulary: 领域常用英文词汇 → 中文（属于「领域语感词」，不是专有名词，
 *                          用于扩大本地关键词匹配召回，避免漏词）
 *      两者分离，是为了满足需求中「不要因为某个词在领域中常见，就强行把它
 *      包装成领域术语」——命中判定比对话展示更严格。
 *
 * 结构：
 *   INTEREST_DOMAINS: { [domainId]: DomainConfig }
 *   DomainConfig = {
 *     id, name, subtitle, description,
 *     icon,                       // 领域选择器上的图形字符（非 emoji 装饰亦可）
 *     theme,                      // 视觉主题 token
 *     domainTerms,                // 专有名词 → 官方中文译名
 *     domainVocabulary,           // 领域常用词 → 中文（用于召回）
 *     domainTermTiers,            // 术语权重分级（可选，影响排序）
 *     excludedTerms,              // 假阳性黑名单（词形相同但领域无关）
 *     generationPrompt,           // AI system prompt（仅供批量预生成，运行时不执行）
 *   }
 *
 * ============================================================================
 * ★★★ 术语严谨性原则（新增领域时必须遵守，不可绕过）★★★
 * ============================================================================
 *
 * 【总原则】预生成材料必须来自该领域的权威专业来源，禁止自行翻译。
 *
 * 1. 译名来源必须是该领域的权威渠道，例如：
 *      - 游戏 / 动漫 / 影视：官方中文（Steam 官方中文、PlayStation 官方中文、
 *        官方设定集、官方中文 Wiki）、Fandom Wiki 中文站、Steam 社区指南
 *      - 中国玩家社区共识：NGA、小黑盒、Bilibili 官号等有较高公信力的社区
 *      - 体育 / 学术 / 行业：官方规则手册、权威教材、行业协会术语表
 *    在 domainTerms 中，每个词必须能对应到「可查证的来源」。
 *
 * 2. 无法确认官方译名时，两个选择（二选一，不得编造）：
 *      a) 直接不在材料中给出译名（在 domainMaterials JSON 里
 *         source 留空 / 说明「未收录」）；
 *      b) 若仍要展示，必须在材料条目上标记 `unverified: true` + `source`
 *         写明来源与不确定性，前端会渲染【译名待确认】角标。
 *    ⚠️ 绝对禁止「自己按字面意思翻译一个像样的中文」然后当作官方译名使用。
 *
 * 3. 每条预生成材料（src/data/domainMaterials/*.json）都必须带两个字段：
 *      source:     string   —— 译名来源说明，例如 'Steam 官方中文' / 'Fandom Wiki'
 *      unverified: boolean  —— 是否无法确认官方译名（true 会显示待确认角标）
 *
 * 4. 反例（本项目已修正过的问题）：
 *      ✗ 'marathon' 曾被自行翻译为「马拉松模式」；
 *        该词在《杀戮尖塔》中指自定义/挑战玩法，官方中文并无「马拉松模式」这一说法，
 *        因此该条材料已改为 unverified: true，不再冒充官方译名。
 *      ✗ 'defect'（故障机器人）曾因词形规则把 'defection'（变节）误判为术语，
 *        已在 excludedTerms 中显式排除。
 *
 * 5. 落地检查清单（加新领域时逐条确认）：
 *      □ domainTerms 中每个词的译名都能指出来源
 *      □ domainVocabulary 只放「领域语感词」，不冒充专有术语
 *      □ excludedTerms 已覆盖会造成假阳性的通用词
 *      □ 预生成材料 JSON 中每条都填了 source，不确定的标了 unverified: true
 *      □ generationPrompt 中已写明「禁止自行翻译，不确定就标注待确认」
 * ============================================================================
 */

